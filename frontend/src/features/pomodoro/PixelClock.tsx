const digits: Record<string, string[]> = {
  '0': ['01110', '11011', '11011', '11011', '11011', '11011', '01110'],
  '1': ['00110', '01110', '00110', '00110', '00110', '00110', '11111'],
  '2': ['11110', '00011', '00011', '01110', '11000', '11000', '11111'],
  '3': ['11110', '00011', '00011', '01110', '00011', '00011', '11110'],
  '4': ['11011', '11011', '11011', '11111', '00011', '00011', '00011'],
  '5': ['11111', '11000', '11000', '11110', '00011', '00011', '11110'],
  '6': ['01110', '11000', '11000', '11110', '11011', '11011', '01110'],
  '7': ['11111', '00011', '00110', '00110', '01100', '01100', '01100'],
  '8': ['01110', '11011', '11011', '01110', '11011', '11011', '01110'],
  '9': ['01110', '11011', '11011', '01111', '00011', '00011', '01110'],
  ':': ['0', '1', '1', '0', '1', '1', '0'],
};
const positions = [0, 6, 12, 14, 20];

export function PixelClock({ time }: { time: string }) {
  return (
    <div
      className="pixel-clock"
      role="timer"
      aria-label={`${time} remaining`}
      aria-live="off"
    >
      <svg
        viewBox="-1 -1 27 9"
        aria-hidden="true"
        focusable="false"
        shapeRendering="crispEdges"
      >
        {time
          .split('')
          .flatMap((digit, index) =>
            (digits[digit] ?? []).flatMap((row, y) =>
              row
                .split('')
                .map((pixel, x) =>
                  pixel === '1' ? (
                    <rect
                      key={`${index}-${x}-${y}`}
                      x={(positions[index] ?? 0) + x}
                      y={y}
                      width="1"
                      height="1"
                      fill="currentColor"
                    />
                  ) : null,
                ),
            ),
          )}
      </svg>
    </div>
  );
}
